// 날짜 고르기 규칙 확인: node supabase/functions/read-expiry/parse.test.ts
import { pickExpiry } from './parse.ts'

const today = '2026-11-27'
const cases: [string, string, string | null][] = [
  ['유통기한 표시', '유통기한: 2026.12.15', '2026-12-15'],
  ['까지 표시', '26.12.15까지', '2026-12-15'],
  ['제조일과 유통기한 함께', '제조일자 2026.06.15\n유통기한 2026.12.15', '2026-12-15'],
  ['순서가 거꾸로', '유통기한 2027.01.10 제조일자 2026.07.10', '2027-01-10'],
  ['소비기한 8자리', '소비기한 20261203 까지', '2026-12-03'],
  ['연월일 글자', '소비기한: 2026년 12월 3일까지', '2026-12-03'],
  ['EXP 영문', 'EXP 2026/12/20', '2026-12-20'],
  ['표시 없이 날짜만 하나', '26.12.04', '2026-12-04'],
  ['표시 없이 날짜 둘 (늦은 쪽)', '26.06.04\n26.12.04', '2026-12-04'],
  ['제조일만', '제조일 2026.11.01', null],
  ['없는 날짜', '유통기한 2026.13.40', null],
  ['날짜 없음', '신라면 120g 5개입', null],
  ['가격·바코드 섞임', '1,500원 8801043014830\n유통기한 2026.12.15 까지', '2026-12-15'],
  ['전각 숫자', '유통기한 ２０２６．１２．１５', '2026-12-15'],
  ['띄어쓴 표시', '유 통 기 한 26. 12. 15', '2026-12-15'],
]

let fail = 0
for (const [name, text, want] of cases) {
  const got = pickExpiry(text, today)
  const ok = got.iso === want
  if (!ok) fail++
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}: ${got.iso ?? `없음 (${'note' in got ? got.note : ''})`}${ok ? '' : `  (기대: ${want})`}`)
}
console.log(fail === 0 ? `\n전부 통과 (${cases.length}개)` : `\n${fail}개 실패`)
if (fail) process.exit(1)
